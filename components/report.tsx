"use client";
// Customer Discovery Evidence Report (FR-30-32)
import type { DiscoverySession } from "@/lib/types";
import { ACTION_LABEL } from "@/lib/types";
import { activeHypotheses, countsAsEvidence, realEvidenceCount } from "@/lib/rules";
import { HTYPE_LABEL } from "./panels";
import { download } from "./ui";

export function buildMarkdown(s: DiscoverySession) {
  const v = s.venture;
  const act = activeHypotheses(s).filter((h) => h.approved).sort((a, b) => a.priority - b.priority);
  const decided = s.recommendations.filter((r) => r.decision !== "pending");
  const latest = decided[decided.length - 1] || s.recommendations[s.recommendations.length - 1];
  const L: string[] = [];
  L.push(`# Customer Discovery Evidence Report - ${s.title}`, "", `Generated by VumbuaAI on ${new Date().toLocaleString("en-GB")}. AI assessments are guidance, not verified fact. Hypothesis statuses are computed by fixed rules from recorded real-customer evidence.`, "");
  L.push("## 1. Venture", `- Idea: ${v.idea || "-"}`, `- Proposed solution: ${v.solution || "-"}`, `- Target customer: ${v.targetCustomer || "-"}`, `- Stage: ${v.stage || "-"}`, `- Segments: ${v.segments.join("; ") || "-"}`, `- Early adopters: ${v.earlyAdopters.join("; ") || "-"}`, `- Problems: ${v.problems.join("; ") || "-"}`, `- Existing alternatives: ${v.alternatives.join("; ") || "-"}`, `- Unmet needs: ${v.unmetNeeds.join("; ") || "-"}`, "");
  L.push("## 2. Hypotheses and status", "| # | Type | Hypothesis | Status | Supporting | Contradicting |", "|---|---|---|---|---|---|");
  act.forEach((h, i) => {
    const ev = s.evidence.filter((e) => e.hypothesisId === h.id && countsAsEvidence(e));
    L.push(`| ${i + 1} | ${HTYPE_LABEL[h.type]} | ${h.statement} | ${h.status} | ${ev.filter((e) => e.direction === "supports").length} | ${ev.filter((e) => e.direction === "contradicts").length} |`);
  });
  const revs = s.hypotheses.filter((h) => h.supersededBy);
  if (revs.length) { L.push("", "Revised hypotheses:"); revs.forEach((h) => { const n = s.hypotheses.find((x) => x.id === h.supersededBy); L.push(`- "${h.statement}" -> "${n?.statement}"${n?.revisionReason ? ` (${n.revisionReason})` : ""}`); }); }
  L.push("", "## 3. Interview findings");
  const interviews = [...new Set(s.evidence.map((e) => e.interviewRef))];
  if (!s.evidence.length) L.push("No interviews recorded. All hypotheses remain untested.");
  interviews.forEach((iv) => {
    L.push(`### ${iv}`);
    s.evidence.filter((e) => e.interviewRef === iv).forEach((e) => L.push(`- [${e.direction}] [${e.kind}]${e.simulated ? " [SIMULATED - excluded]" : ""} ${e.observation} (ref ${e.id})`));
  });
  L.push("", "## 4. Evidence assessments (AI guidance)");
  if (!s.findings.length) L.push("No assessments yet.");
  s.findings.forEach((f) => {
    const h = s.hypotheses.find((x) => x.id === f.hypothesisId);
    L.push(`### ${h?.statement}`, f.summary, `- Supporting evidence: ${f.supportingIds.join(", ") || "none"}`, `- Contradicting evidence: ${f.contradictingIds.join(", ") || "none"}`, `- Gaps: ${f.gaps.join("; ") || "none"}`, ...f.ruleNotes.map((n) => `- Rules engine: ${n}`));
  });
  L.push("", "## 5. Contradictions");
  const con = s.evidence.filter((e) => countsAsEvidence(e) && e.direction === "contradicts");
  if (!con.length) L.push("None recorded."); con.forEach((e) => L.push(`- ${e.observation} (${e.interviewRef}; against: ${s.hypotheses.find((h) => h.id === e.hypothesisId)?.statement})`));
  L.push("", "## 6. Decisions");
  if (!s.recommendations.length) L.push("No recommendations yet.");
  s.recommendations.forEach((r) => L.push(`- ${ACTION_LABEL[r.action]} - ${r.decision.toUpperCase()}${r.founderNote ? ` - founder note: ${r.founderNote}` : ""}`, `  - Rationale: ${r.rationale}`, `  - Uncertainty: ${r.uncertainty}`));
  L.push("", "## 7. Recommended next action");
  if (latest) {
    L.push(`**${ACTION_LABEL[latest.action]}** (${latest.decision})`, latest.experiment ? `Next experiment: ${latest.experiment}` : "", latest.unresolved.length ? `Unresolved assumptions: ${latest.unresolved.join("; ")}` : "");
  } else if (realEvidenceCount(s) === 0) L.push("**Continue discovery** - interview real customers; no hypothesis has been tested yet.");
  else L.push("Ask VumbuaAI for an assessment and record your decision.");
  return L.filter((x) => x !== undefined).join("\n");
}

export function ReportPanel({ s }: { s: DiscoverySession }) {
  const v = s.venture;
  const act = activeHypotheses(s).filter((h) => h.approved).sort((a, b) => a.priority - b.priority);
  const con = s.evidence.filter((e) => countsAsEvidence(e) && e.direction === "contradicts");
  const decided = s.recommendations.filter((r) => r.decision !== "pending");
  const latest = decided[decided.length - 1] || s.recommendations[s.recommendations.length - 1];
  const interviews = [...new Set(s.evidence.map((e) => e.interviewRef))];
  const fname = s.title.replace(/\W+/g, "-");

  return (
    <div className="stack">
      <div className="row no-print" style={{ justifyContent: "space-between" }}>
        <h2 style={{ margin: 0 }}>Evidence report</h2>
        <div className="row">
          <button className="btn-primary" onClick={() => window.print()}>Download PDF</button>
          <button onClick={() => download(`${fname}-discovery-report.md`, buildMarkdown(s), "text/markdown")}>Download Markdown</button>
        </div>
      </div>
      <p className="muted no-print">"Download PDF" opens your browser's print dialog - choose "Save as PDF".</p>

      <article id="report" className="card report">
        <h1>Customer Discovery Evidence Report</h1>
        <p><strong>{s.title}</strong> - generated by VumbuaAI on {new Date().toLocaleString("en-GB")}</p>
        <p className="ai-note">AI assessments in this report are guidance, not verified fact. Hypothesis statuses are computed by fixed rules from recorded real-customer evidence; simulated responses and founder interpretations are excluded.</p>

        <h2>1. Venture</h2>
        <table><tbody>
          {[["Idea", v.idea], ["Proposed solution", v.solution], ["Target customer", v.targetCustomer], ["Stage", v.stage],
            ["Customer segments", v.segments.join("; ")], ["Early adopters", v.earlyAdopters.join("; ")], ["Problems", v.problems.join("; ")],
            ["Existing alternatives", v.alternatives.join("; ")], ["Unmet needs", v.unmetNeeds.join("; ")]].map(([k, val]) => (
            <tr key={k}><th style={{ width: "28%" }}>{k}</th><td>{val || "-"}</td></tr>))}
        </tbody></table>

        <h2>2. Hypotheses and status</h2>
        {act.length ? (
          <table><thead><tr><th>#</th><th>Type</th><th>Hypothesis</th><th>Status</th><th>Sup.</th><th>Con.</th></tr></thead><tbody>
            {act.map((h, i) => { const ev = s.evidence.filter((e) => e.hypothesisId === h.id && countsAsEvidence(e)); return (
              <tr key={h.id}><td>{i + 1}</td><td>{HTYPE_LABEL[h.type]}</td><td>{h.statement}</td><td>{h.status}</td>
                <td>{ev.filter((e) => e.direction === "supports").length}</td><td>{ev.filter((e) => e.direction === "contradicts").length}</td></tr>); })}
          </tbody></table>
        ) : <p>No approved hypotheses.</p>}
        {s.hypotheses.some((h) => h.supersededBy) && (<><h3 style={{ marginTop: 10 }}>Revisions</h3><ul>
          {s.hypotheses.filter((h) => h.supersededBy).map((h) => { const n = s.hypotheses.find((x) => x.id === h.supersededBy); return <li key={h.id}><s>{h.statement}</s> &rarr; {n?.statement} {n?.revisionReason && <em>({n.revisionReason})</em>}</li>; })}
        </ul></>)}

        <h2>3. Interview findings</h2>
        {!interviews.length && <p><strong>No interviews recorded. All hypotheses remain untested.</strong></p>}
        {interviews.map((iv) => (
          <div key={iv}><h3 style={{ marginTop: 10 }}>{iv}</h3><table><tbody>
            {s.evidence.filter((e) => e.interviewRef === iv).map((e) => (
              <tr key={e.id}><td style={{ width: "16%" }}>{e.direction}</td><td style={{ width: "18%" }}>{e.kind}{e.simulated ? " (SIMULATED - excluded)" : ""}</td><td>{e.observation}</td><td style={{ width: "12%" }}><small>{e.id}</small></td></tr>))}
          </tbody></table></div>
        ))}

        <h2>4. Evidence assessments (AI guidance)</h2>
        {!s.findings.length && <p>No assessments yet.</p>}
        {s.findings.map((f) => (
          <div key={f.id}><h3 style={{ marginTop: 10 }}>{s.hypotheses.find((h) => h.id === f.hypothesisId)?.statement}</h3>
            <p>{f.summary}</p>
            <p><small>Supporting: {f.supportingIds.join(", ") || "none"} | Contradicting: {f.contradictingIds.join(", ") || "none"}</small></p>
            {f.gaps.length > 0 && <p><small>Gaps: {f.gaps.join("; ")}</small></p>}
            {f.ruleNotes.map((n, i) => <p key={i}><small>Rules engine: {n}</small></p>)}
          </div>
        ))}

        <h2>5. Contradictions</h2>
        {con.length ? <ul>{con.map((e) => <li key={e.id}>{e.observation} <small>({e.interviewRef}; against "{s.hypotheses.find((h) => h.id === e.hypothesisId)?.statement}")</small></li>)}</ul> : <p>None recorded.</p>}

        <h2>6. Decisions</h2>
        {s.recommendations.length ? (
          <table><thead><tr><th>Recommendation</th><th>Founder decision</th><th>Rationale and uncertainty</th></tr></thead><tbody>
            {s.recommendations.map((r) => (<tr key={r.id}><td>{ACTION_LABEL[r.action]}</td><td>{r.decision}{r.founderNote ? ` - ${r.founderNote}` : ""}</td><td>{r.rationale}<br /><em>Uncertainty: {r.uncertainty}</em></td></tr>))}
          </tbody></table>
        ) : <p>No recommendations yet.</p>}

        <h2>7. Recommended next action</h2>
        {latest ? (<>
          <p><strong>{ACTION_LABEL[latest.action]}</strong> ({latest.decision === "pending" ? "awaiting founder decision" : `founder ${latest.decision}`})</p>
          {latest.experiment && <p>Next experiment: {latest.experiment}</p>}
          {latest.unresolved.length > 0 && <p>Unresolved assumptions: {latest.unresolved.join("; ")}</p>}
        </>) : realEvidenceCount(s) === 0
          ? <p><strong>Continue discovery</strong> - interview real customers; no hypothesis has been tested yet.</p>
          : <p>Ask VumbuaAI for an assessment and record your decision.</p>}
      </article>
    </div>
  );
}
